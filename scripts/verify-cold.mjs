import assert from 'node:assert/strict';
import {coldDuplicate,coldStockAt,coldSummary} from '../lib/cold-storage.ts';
import {createColdPdf} from '../lib/cold-pdf.ts';
import {writeFileSync} from 'node:fs';

const purchase={id:'p1',product:'Limon',person:'Murat',plate:'33 ABC 123',kg:10000,price:12,dateTime:'2026-09-01T09:00:00Z',note:'',status:'active'};
const sale={id:'s1',product:'Limon',buyer:'GETA',kg:8000,price:18,dateTime:'2026-09-02T09:00:00Z',note:'',status:'active'};
const expense={id:'e1',title:'Elektrik',category:'Elektrik',amount:1000,dateTime:'2026-09-02T09:00:00Z',note:''};
const state={purchases:[purchase],sales:[sale],expenses:[expense],categories:[]};
const summary=coldSummary(state);
assert.equal(summary.buyCost,120000);
assert.equal(summary.revenue,144000);
assert.equal(summary.stockKg,2000);
assert.equal(summary.costOfGoods,96000);
assert.equal(summary.profit,47000);
assert.equal(summary.profitPerKg,5.875);
assert.equal(coldStockAt(state,'Limon'),2000);
assert.equal(coldStockAt(state,'Portakal'),0);
assert.equal(coldSummary(state,Date.parse('2026-09-02T00:00:00Z'),Date.parse('2026-09-03T00:00:00Z')).profit,47000);
assert.equal(coldSummary({...state,purchases:[{...purchase,status:'cancelled'}]}).buyKg,0);
assert.equal(coldSummary({...state,sales:[{...sale,status:'cancelled'}]}).saleKg,0);
assert.equal(coldDuplicate(state.purchases,{...purchase,id:'p2',dateTime:'2026-09-01T09:04:00Z'}),true);
assert.equal(coldDuplicate(state.sales,{...sale,id:'s2',dateTime:'2026-09-02T09:10:00Z'}),false);
assert.equal(coldSummary({...state,purchases:[purchase,{...purchase,id:'p3',person:'Ahmet',kg:10000,price:14,dateTime:'2026-09-03T09:00:00Z'}],sales:[sale,{...sale,id:'s3',kg:1000,price:20,dateTime:'2026-09-04T09:00:00Z'}],expenses:[]}).costOfGoods,109666.66666666667);
assert.equal(coldSummary({...state,purchases:[purchase,{...purchase,id:'case',product:'limon',kg:1000}]}).buyKg,11000);
const report=createColdPdf(state,-Infinity,Infinity,'Test');
assert.ok(report.startsWith('%PDF-1.4'));
assert.ok(report.includes('SOGUK HAVA DEPOSU'));
assert.ok(report.includes('ALIS OZETI'));
writeFileSync('/tmp/gurminik-cold-test.pdf',report);
console.log('Soğuk Hava kontrolleri: ağırlıklı maliyet, stok, kâr, gider, dönem, iptal ve çift kayıt başarılı.');
